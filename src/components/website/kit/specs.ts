const round10 = (n: number) => Math.round(n / 10) * 10;
function groups(menu: Menu, mult = 1): ServiceGroup[] {
  return menu.map(([name, items]) => ({
    name: cz(name),
    items: items.map(([n, min, price, desc, from]) => ({
      name: cz(n),
      desc: desc ? cz(desc) : undefined,
      min,
      price: price < 300 ? price : round10(price * mult),
      from,
    })),
  }));
}

function build(s: Spec, i: number): TemplateContent {
  const nav = NAV[s.kind];
  const values = VALUES[s.kind === "beauty" ? "beauty" : s.kind];
  const gal = s.photos.gallery;
  return {
    slug: s.slug,
    name: s.name,
    motif: s.motif,
    card: { type: t4(...s.card[0]), style: t4(...s.card[1]) },
    tagline: cz(s.tagline),
    nav: { "": cz(nav[0]), "dich-vu": cz(nav[1]), "gioi-thieu": cz(nav[2]), "bo-suu-tap": cz(nav[3]), "dat-lich": cz(nav[4]) },
    bookLabel: cz("Rezervovat"),
    home: {
      kicker: cz(s.kicker),
      title: cz(s.title),
      lead: cz(s.lead),
      hero: pic(0, s.photos.hero),
      intro: { title: cz(s.intro[0]), text: cz(s.intro[1]) },
      highlights: s.hl.map(([a, b]) => ({ title: cz(a), text: cz(b) })),
      featured: [
        [0, 0],
        [0, 1],
        [1, 0],
      ],
      closing: { title: cz(s.closing[0]), text: cz(s.closing[1]) },
    },
    services: {
      title: cz(nav[1]),
      lead: cz("Ceny jsou orientační. Přesnou cenu upřesníme při konzultaci."),
      groups: groups(MENUS[s.menu] as Menu, s.mult),
      note: cz("Ukázkové ceny v Kč. Platit můžete kartou i hotově."),
    },
    about: {
      title: cz(s.kind === "barber" ? "Naši barbeři" : "O nás"),
      lead: cz(s.tagline),
      story: [cz(s.story)],
      team: s.team.map(([name, role, bio], k) => ({ name, role: cz(role), bio: cz(bio), visual: pic(k, s.photos.team[k % s.photos.team.length]) })),
      values: values.map(([a, b]) => ({ title: cz(a), text: cz(b) })),
    },
    gallery: { title: cz("Galerie"), lead: cz("Ukázky naší práce a atmosféry."), items: gal.map((p, k) => pic(k % 4, p)) },
    contact: {
      title: cz("Rezervace"),
      lead: cz("Vyberte službu a čas, termín vám potvrdíme."),
      address: s.address,
      hours: (s.hours ?? [["Po – Pá", "9:00 – 20:00"], ["So", "9:00 – 14:00"]]).map(([d, time]) => ({ days: cz(d), time })),
      phone: `+420 123 456 ${String(820 + i)}`,
      email: `ahoj@${s.slug}.example`,
    },
  };
}

